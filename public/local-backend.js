  async function put(store, value) {
    const db = await openDb();
    const t = db.transaction(store, 'readwrite');
    t.objectStore(store).put(value);
    await new Promise((res, rej) => { t.oncomplete = res; t.onerror = () => rej(t.error); });
    return value;
  }
